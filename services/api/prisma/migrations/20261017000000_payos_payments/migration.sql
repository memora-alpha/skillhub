BEGIN;
ALTER TYPE "PaymentStatus" ADD VALUE IF NOT EXISTS 'REVIEW';
ALTER TABLE credit_wallets ADD COLUMN provenance_tracked BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE credit_operations ADD COLUMN instruction_digest CHAR(64);
-- Only empty wallets have unambiguous provenance. Funded legacy wallets need an operator-reviewed manifest.
UPDATE credit_wallets SET provenance_tracked = true
WHERE available_credit = 0 AND held_credit = 0 AND purchased_credit = 0 AND bonus_credit = 0;

CREATE TABLE payos_checkouts (
 payment_id UUID PRIMARY KEY REFERENCES payments(payment_id) ON DELETE RESTRICT ON UPDATE RESTRICT,
 channel VARCHAR(100) NOT NULL,
 order_code BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000 MAXVALUE 9007199254740991) UNIQUE NOT NULL,
 payment_link_id VARCHAR(255), qr_code VARCHAR(4096),
 state VARCHAR(24) NOT NULL DEFAULT 'PREPARING' CHECK (state IN ('PREPARING','READY','CLOSED','REVIEW')),
 version INTEGER NOT NULL DEFAULT 1 CHECK (version > 0),
 quote_digest CHAR(64) NOT NULL,
 policy_version VARCHAR(40) NOT NULL,
 expires_at TIMESTAMPTZ(3) NOT NULL, paid_at TIMESTAMPTZ(3),
 top_up_operation_id UUID UNIQUE REFERENCES credit_operations(operation_id) ON DELETE RESTRICT,
 last_error VARCHAR(80), attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 lease_until TIMESTAMPTZ(3), lease_token UUID,
 return_url TEXT NOT NULL, cancel_url TEXT NOT NULL,
 created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(channel,payment_link_id)
);
CREATE INDEX payos_checkouts_next_attempt_at_idx ON payos_checkouts(next_attempt_at);
CREATE TABLE payment_receipts (
 id UUID PRIMARY KEY, channel VARCHAR(100) NOT NULL, transaction_id VARCHAR(255) NOT NULL,
 digest CHAR(64) NOT NULL, evidence JSONB NOT NULL,
 payment_id UUID REFERENCES payments(payment_id) ON DELETE RESTRICT,
 state VARCHAR(24) NOT NULL CHECK (state IN ('POSTED','REVIEW')),
 reason VARCHAR(80), conflict BOOLEAN NOT NULL DEFAULT false,
 created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(channel,transaction_id)
);
CREATE INDEX payment_receipts_payment_id_idx ON payment_receipts(payment_id);
CREATE TABLE payment_findings (
 id UUID PRIMARY KEY, receipt_id UUID NOT NULL REFERENCES payment_receipts(id) ON DELETE RESTRICT,
 digest CHAR(64) NOT NULL, evidence JSONB NOT NULL, reason VARCHAR(80) NOT NULL,
 created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(receipt_id,digest)
);
CREATE TABLE credit_lots (
 id UUID PRIMARY KEY, user_id UUID NOT NULL REFERENCES credit_wallets(user_id) ON DELETE RESTRICT,
 operation_id UUID NOT NULL UNIQUE REFERENCES credit_operations(operation_id) ON DELETE RESTRICT,
 source VARCHAR(20) NOT NULL CHECK (source IN ('PURCHASED','BONUS','EARNED')),
 available BIGINT NOT NULL, held BIGINT NOT NULL DEFAULT 0, consumed BIGINT NOT NULL DEFAULT 0,
 granted BIGINT NOT NULL, created_at TIMESTAMPTZ(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK (available >= 0 AND held >= 0 AND consumed >= 0 AND granted > 0),
 CHECK (available + held + consumed = granted)
);
CREATE INDEX credit_lots_user_id_created_at_id_idx ON credit_lots(user_id,created_at,id);
CREATE TABLE credit_lot_holds (
 allocation_id UUID NOT NULL REFERENCES held_credit_allocations(allocation_id) ON DELETE RESTRICT,
 lot_id UUID NOT NULL REFERENCES credit_lots(id) ON DELETE RESTRICT,
 amount BIGINT NOT NULL CHECK (amount > 0), remaining BIGINT NOT NULL,
 PRIMARY KEY(allocation_id,lot_id), CHECK (remaining >= 0 AND remaining <= amount)
);
COMMIT;
